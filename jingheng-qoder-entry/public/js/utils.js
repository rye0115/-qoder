export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function attr(value) {
  return esc(value).replace(/`/g, '&#96;');
}

export function fmt(value, suffix = '') {
  if (value == null || !Number.isFinite(Number(value))) return '—';
  const n = Number(value);
  return `${Number.isInteger(n) ? n : n.toFixed(1)}${suffix}`;
}

export function pct(value) {
  if (value == null) return '—';
  return `${Math.round(value)}%`;
}

export function dateCn(value) {
  if (!value) return '日期待核';
  const m = String(value).match(/(20\d{2})[-/.年](\d{1,2})[-/.月](\d{1,2})?/);
  if (!m) return String(value);
  return `${m[1]}.${String(m[2]).padStart(2, '0')}${m[3] ? `.${String(m[3]).padStart(2, '0')}` : ''}`;
}

export function relativeTime(iso) {
  if (!iso) return '';
  const t = new Date(iso).getTime();
  if (!Number.isFinite(t)) return '';
  const diff = Math.max(0, Date.now() - t);
  if (diff < 60_000) return '刚刚';
  if (diff < 3600_000) return `${Math.floor(diff / 60000)} 分钟前`;
  if (diff < 86400_000) return `${Math.floor(diff / 3600_000)} 小时前`;
  return `${Math.floor(diff / 86400_000)} 天前`;
}

export function safeUrl(url) {
  try {
    const u = new URL(url);
    return ['http:', 'https:'].includes(u.protocol) ? u.toString() : '';
  } catch {
    return '';
  }
}

export function hostLabel(url) {
  try { return new URL(url).hostname.replace(/^www\./, ''); } catch { return ''; }
}

